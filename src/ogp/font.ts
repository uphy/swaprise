export const CARD_GLYPH_W = 5;
export const CARD_GLYPH_H = 7;
export const CARD_LETTER_GAP = 1;

/** 文字列をドット文字で描ける形に寄せる。小文字は大文字、字形のない文字は ? */
export function cardText(text: string): string {
  return Array.from(text.toUpperCase(), (ch) => (CARD_FONT[ch] ? ch : "?")).join("");
}

/** 文字列の幅（マス）。 */
export function cardTextCols(text: string): number {
  return text.length === 0 ? 0 : text.length * (CARD_GLYPH_W + CARD_LETTER_GAP) - CARD_LETTER_GAP;
}
